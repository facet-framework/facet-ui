import {
  readdirSync,
  readFileSync,
  mkdirSync,
  writeFileSync,
  copyFileSync,
  existsSync,
  unlinkSync,
} from "node:fs";
import { join } from "node:path";

// Inventory exact installed lockfile versions. Build metafiles identify bundled modules.
const lock = readFileSync("pnpm-lock.yaml", "utf8");
const locked = new Set(
  [...lock.matchAll(/^ {2}['"]?([^\s'"()]+@[^\s:'"()]+)['"]?:/gm)].map((m) => m[1]),
);
const meta = JSON.parse(readFileSync("dist/metafile-esm.json", "utf8"));
const bundled = new Set(
  Object.keys(meta.inputs).flatMap((input) => {
    const parts = input.split("/node_modules/");
    if (parts.length < 2) return [];
    const pieces = parts.at(-1).split("/");
    return [pieces[0].startsWith("@") ? pieces.slice(0, 2).join("/") : pieces[0]];
  }),
);
const bundledKeys = new Set(
  Object.keys(meta.inputs).flatMap((input) => {
    const marker = "/node_modules/";
    const index = input.lastIndexOf(marker);
    if (index < 0) return [];
    const tail = input.slice(index + marker.length).split("/");
    const name = tail[0].startsWith("@") ? tail.slice(0, 2).join("/") : tail[0];
    const root = input.slice(0, index + marker.length) + name;
    const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
    return [`${pkg.name}@${pkg.version}`];
  }),
);
const packages = new Map();
for (const folder of readdirSync("node_modules/.pnpm")) {
  const modules = join("node_modules/.pnpm", folder, "node_modules");
  if (!existsSync(modules)) continue;
  for (const scope of readdirSync(modules)) {
    if (scope.startsWith(".")) continue;
    const names = scope.startsWith("@")
      ? readdirSync(join(modules, scope)).map((n) => `${scope}/${n}`)
      : [scope];
    for (const name of names) {
      const root = join(modules, name),
        file = join(root, "package.json");
      if (!existsSync(file)) continue;
      const p = JSON.parse(readFileSync(file, "utf8")),
        key = `${p.name}@${p.version}`;
      if (!locked.has(key) || packages.has(key)) continue;
      const license = typeof p.license === "string" ? p.license : p.license?.type;
      if (!license) throw new Error(`Missing license metadata: ${key}`);
      const texts = readdirSync(root).filter((f) =>
        /^(licen[sc]e|copying|notice)(\.|$|-)/i.test(f),
      );
      const shipped = bundledKeys.has(key);
      if (shipped && (/\b(?:AGPL|GPL)-/.test(license) || !texts.length))
        throw new Error(`Review shipped license: ${key}: ${license}`);
      packages.set(key, { name: p.name, version: p.version, license, root, texts, shipped });
    }
  }
}
for (const key of bundledKeys)
  if (!packages.has(key)) throw new Error(`Uninventoried bundle input: ${key}`);
mkdirSync("dist/licenses", { recursive: true });
for (const p of packages.values())
  if (p.shipped) {
    const dest = join("dist/licenses", `${p.name.replaceAll("/", "-")}@${p.version}`);
    mkdirSync(dest, { recursive: true });
    for (const text of p.texts) copyFileSync(join(p.root, text), join(dest, text));
  }
const list = [...packages.values()].sort((a, b) =>
  `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`, "en"),
);
const header =
  "# Third-party dependencies\n\nGenerated by `pnpm run licenses:generate` from pnpm-lock.yaml and installed package metadata.\nBundled modules are verified against the standalone build metafile. License texts\nfor bundled packages are included in `dist/licenses/` and the npm package.\nReact and React DOM are also peer dependencies supplied by React consumers.\nDevelopment dependencies are not shipped. Platform-specific optional tools absent\nfrom this Linux installation are not inventoried here. Third-party terms remain\nin force independently of the project’s Apache-2.0 license.\n\n";
const table = "| Package | Version | License | Use |\n| --- | --- | --- | --- |\n";
const rows = (values) =>
  values
    .map(
      (p) =>
        `| ${p.name} | ${p.version} | ${p.license.replaceAll("|", "\\|")} | ${p.shipped ? "Bundled runtime" : "Development"} |`,
    )
    .join("\n") + "\n";
writeFileSync("THIRD_PARTY.md", header + table + rows(list));
writeFileSync("dist/THIRD_PARTY.md", header + table + rows(list.filter((p) => p.shipped)));
writeFileSync(
  "NOTICE",
  "FACET UI\nCopyright 2026 Pascal Malbranche\n\nLicensed under the Apache License, Version 2.0; see LICENSE.\nBundled third-party software: " +
    list
      .filter((p) => p.shipped)
      .map((p) => `${p.name}@${p.version} (${p.license})`)
      .join(", ") +
    ".\nLicense texts are included in dist/licenses/. See THIRD_PARTY.md.\n",
);
copyFileSync("NOTICE", "dist/NOTICE");
console.log(
  `${list.length} dependency versions verified; bundled: ${[...bundled].sort().join(", ")}`,
);

for (const file of readdirSync("dist"))
  if (/^metafile-.*\.json$/.test(file)) unlinkSync(join("dist", file));
