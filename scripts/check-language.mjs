export function outsideValues(file, source) {
  const variable = catalogues.get(file);
  if (!variable) return source;
  const parsed = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const spans = [];
  function visit(node) {
    if (
      ts.isVariableDeclaration(node) &&
      node.name.getText(parsed) === variable &&
      node.initializer &&
      ts.isObjectLiteralExpression(node.initializer)
    ) {
      for (const property of node.initializer.properties) {
        if (ts.isPropertyAssignment(property) && ts.isStringLiteral(property.initializer)) {
          spans.push([property.initializer.getStart(parsed), property.initializer.end]);
        }
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(parsed);
  for (const [start, end] of spans.reverse())
    source =
      source.slice(0, start) + source.slice(start, end).replace(/[^\n]/g, " ") + source.slice(end);
  return source;
}

export function scan(file, source) {
  const text = outsideValues(file, source);
  const tokens = [...text.matchAll(wordPattern)];
  const accents = [...text.matchAll(marks)].filter(
    (mark) =>
      !tokens.some((word) => mark.index >= word.index && mark.index < word.index + word[0].length),
  );
  return [
    ...tokens.map((match) => ({ match, kind: "word" })),
    ...accents.map((match) => ({ match, kind: "mark" })),
  ].map(({ match, kind }) => ({
    file,
    line: text.slice(0, match.index).split("\n").length,
    column: match.index - text.lastIndexOf("\n", match.index),
    kind,
    text: match[0],
  }));
}

// SPDX identifiers in generated license inventories are English legal metadata.
// Keep these raw lexical matches visible in reports; no source file is exempt.
export function licenseIdentifier(hit, source) {
  if (
    hit.text !== String.fromCodePoint(77, 73, 84) ||
    !["THIRD_PARTY.md", "NOTICE"].includes(hit.file)
  )
    return false;
  const line = source.split("\n")[hit.line - 1];
  return hit.file === "THIRD_PARTY.md"
    ? /^\| [^|]+ \| [^|]+ \| (?:M[I]T(?:-0)?|\(M[I]T OR [^)]+\)) \| (?:Development|Bundled runtime) \|$/.test(
        line,
      )
    : /^Bundled third-party software: .+ \(M[I]T\)(?:, .+ \(M[I]T\))*\.$/.test(line);
}

export function scanTracked(root = process.cwd()) {
  const files = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" })
    .split("\0")
    .filter(Boolean);
  return files.flatMap((file) => {
    const source = readFileSync(resolve(root, file), "utf8");
    return scan(file, source).filter((hit) => !licenseIdentifier(hit, source));
  });
}

